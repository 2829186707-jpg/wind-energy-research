H2('7.2 LCOE与IRR测算模板')
P('度电成本（LCOE）的简化公式：LCOE≈（初始投资×资本回收系数+年运维成本）/年发电量。以海上风电为例：单位投资12000元/kW，25年运营期，WACC 6.5%，资本回收系数约0.081，年固定运维约120元/kW，利用小时3400小时，则LCOE≈（12000×0.081+120）/3400≈（972+120）/3400≈0.32元/kWh，与行业口径（海风度电成本约0.3-0.4元/kWh）一致；陆上风电LCOE已降至约0.15-0.25元/kWh。')
P('项目全投资IRR的快速估算法：全投资IRR≈（年净现金流/初始投资）的10年回收期近似，更精确用现金流量表折现。以浙江苍南1#海风项目为例（2026年4月公开测算）：执行保障性收购电价0.52元/kWh（含0.1元绿证溢价）、年等效利用小时3420小时、25年运营期、1.5%运维通胀，税后IRR为7.2%，高于同期10年期国债收益率约2.8个百分点。山东半岛南U2项目度电成本已压至0.34元/kWh。')
P('IRR敏感性排序（影响从大到小）：电价＞利用小时＞单位投资＞运维成本。136号文后电价全面入市，使"电价假设"成为IRR测算的最大不确定性——电价每降0.02元/kWh，IRR约下降1-1.5个百分点；利用小时每降200小时，IRR约下降1个百分点。这也是市场对海风项目评估分歧的根源：不同电价假设下，同一项目IRR可在5%-8%之间大幅波动。')
