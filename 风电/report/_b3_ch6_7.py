def set_font(run, cn='宋体', en='Arial', size=12, bold=False, color=RGBColor(0,0,0)):
    run.font.name = en
    run._element.rPr.rFonts.set(qn('w:eastAsia'), cn)
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color

def H1(t): doc.add_paragraph(t, style='Heading 1')
def H2(t): doc.add_paragraph(t, style='Heading 2')
def H3(t): doc.add_paragraph(t, style='Heading 3')

def P(t):
    doc.add_paragraph(t)

def B(t):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Pt(0)
    r = p.add_run(t)
    set_font(r, size=12)

def CAP(t):
    c = doc.add_paragraph()
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.space_before = Pt(4)
    c.paragraph_format.space_after = Pt(6)
    r = c.add_run(t)
    set_font(r, cn='宋体', size=10.5, bold=True)

def IMG(path, width_cm=14.5):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(0)
    run = p.add_run()
    run.add_picture(path, width=Cm(width_cm))

def TB(title, headers, rows, widths=None):
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_before = Pt(4)
    cap.paragraph_format.space_after = Pt(4)
    r = cap.add_run(title)
    set_font(r, cn='宋体', size=10.5, bold=True)
    tbl = doc.add_table(rows=1, cols=len(headers))
    tbl.style = 'Table Grid'
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = tbl.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Pt(0)
        p.paragraph_format.line_spacing = 1.0
        run = p.add_run(h)
        set_font(run, cn='宋体', size=10.5, bold=True)
        shd = OxmlElement('w:shd'); shd.set(qn('w:val'),'clear'); shd.set(qn('w:fill'),'D9D9D9')
        hdr[i]._tc.get_or_add_tcPr().append(shd)
    for row in rows:
        cells = tbl.add_row().cells
        for i, v in enumerate(row):
            cells[i].vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            p = cells[i].paragraphs[0]
            p.paragraph_format.first_line_indent = Pt(0)
            p.paragraph_format.line_spacing = 1.0
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER if len(str(v)) <= 12 else WD_ALIGN_PARAGRAPH.LEFT
            run = p.add_run(str(v))
            set_font(run, cn='宋体', size=10.5)
    if widths:
        for i, w in enumerate(widths):
            for row in tbl.rows:
                row.cells[i].width = Cm(w)
    sp = doc.add_paragraph()
    sp.paragraph_format.space_before = Pt(0); sp.paragraph_format.space_after = Pt(0)
    sp.paragraph_format.line_spacing = 1.0; sp.paragraph_format.first_line_indent = Pt(0)
    return tbl

