H1('2 政策与商业模式层：钱从哪里来')

P('风电是政策驱动极强的行业，理解电价形成机制是理解一切盈利模型的钥匙。本章梳理从补贴时代到平价时代、再到2026年“全面入市”的政策演进，并拆解风电运营的商业模式。')

H2('2.1 补贴退坡史：从标杆电价到平价时代')
P('中国风电电价机制经历了四个阶段。第一阶段（2009-2020年）标杆上网电价时代：按资源区划定0.29-0.57元/kWh不等的标杆电价，叠加国家补贴，催生2015年、2020年两轮陆上抢装潮；第二阶段（2021年）平价元年：陆上风电国家补贴正式退出，新建项目执行燃煤基准价；第三阶段（2022-2025年）竞争性配置与市场化交易并存：部分省份以竞价方式分配指标，风电市场化交易电量占比快速提升；第四阶段（2026年起）全面入市：136号文落地，新能源上网电价全面由市场形成。')
P('补贴退坡的直接结果是行业从“政策周期”切换为“成本周期”：装机节奏不再由抢装节点决定，而由项目IRR与电网消纳能力决定。这解释了为什么2022-2024年风电招标量高增但装机波动——开发商在等电价机制明确、等风机价格企稳。理解这条历史线，就能在面试中讲清“为什么2026年是风电商业模式的分水岭”。')

H2('2.2 136号文：新能源全面入市——2026年最大政策变量')
P('2025年发布的136号文（《关于深化新能源上网电价市场化改革促进新能源高质量发展的通知》）是近年来风电领域最重磅的政策，核心是“存量项目机制电价延续、增量项目全面入市”。存量项目：按现有机制电价与差价结算方式执行，逐步过渡；增量项目（2026年起投产）：不再安排固定电价，通过机制电价竞价获得“价差结算”保护，其余电量进入电力市场按现货/中长期价格结算。')
P('对风电商业模式的影响体现在四个层面。第一，收益确定性下降：电价从“锁定”变为“市场波动+机制价差保护”，项目IRR的敏感性显著上升；第二，优质资源向高效开发商集中：机制电价竞价考验开发商对风资源、成本与市场的综合判断，拥有低成本与精细化运营能力的央企（龙源、三峡能源、中广核新能源等）优势扩大；第三，推动“电价+环境溢价”双轮收入：绿电交易、绿证、CCER成为弥补市场化电价下行的重要手段；第四，倒逼产业链降本：电价中枢下行压力沿产业链向上传导，大型化、构网型风机与高效海缆等降本技术的价值进一步凸显。')
P('面试中建议将136号文定位为“从补贴依赖走向市场生存”的成人礼，并主动给出判断：短期压制存量项目估值与新建项目IRR，中长期利好具备成本优势的运营商与能持续降本的设备商——政策出清反而加速行业向头部集中。')

H2('2.3 机制电价竞价、绿电交易与CCER')
P('机制电价竞价是136号文的核心配套工具：地方政府对增量风电项目组织竞价，竞价结果决定项目可获得的机制电价水平与对应的价差结算量。2026年已完成机制电价竞价的省份，纳入机制电价的风电项目规模约7009万千瓦——这部分项目相当于拥有“电价下限保护”，是未来两年最确定的装机底盘。绿电交易方面，风电绿电溢价在部分省份可达0.03-0.08元/kWh，叠加绿证收入，可在一定程度上对冲市场化电价下行；CCER（国家核证自愿减排量）重启后，平价风电项目的碳资产收益重新被市场定价，构成运营商收入的“第三极”。')
P('对研究员而言，需要掌握“电价=市场电价+机制价差+绿电/绿证/CCER溢价”的总框架，并能在给定电价、利用小时、投资成本时快速估算项目IRR。这一能力是私募研究员面试中区分“背书型候选”与“计算型候选”的分水岭，第7章将给出完整测算模板。')

H2('2.4 以大代小/以旧换新/千乡万村驭风：存量市场的新增量')
P('在新建装机之外，存量改造正成为风电需求的重要补充。中国早期安装的风机单机容量小（1.5MW以下）、运行效率低，大批机组进入15-20年寿命周期，具备“以大代小”改造价值——用4-6MW新机组替换老机组，在相同机位下容量可提升2-4倍、利用小时提升30%以上。2026年以来中节能、国家能源集团等央国企陆续启动“以大代小”技改增容招标，市场预计“十五五”期间存量改造年化贡献10-20GW增量。')
P('“千乡万村驭风行动”则打开分散式风电空间：在广大农村地区利用零散土地安装小容量机组，就近消纳、就地并网，2026年已成为整机商中标的重要来源（金风科技在河北、内蒙古等地斩获多个分散式项目）。叠加“以旧换新”政策对老旧风机的置换补贴，存量市场为整机与零部件企业提供了穿越新建装机波动的缓冲垫。')

H2('2.5 运营商业模式拆解：电价×利用小时×IRR')
P('风电运营是典型的重资产、现金流型生意，收入=装机容量×利用小时×上网电价，成本以折旧（占比约40%-50%）与运维为主，边际成本极低。运营商的盈利弹性主要来自三处：利用小时提升（风资源评估、智能运维）、电价结构优化（绿电交易比例提升）、财务费用下降（利率下行周期中高杠杆项目的利润释放）。')
P('IRR视角下，典型陆上风电项目全投资IRR约6%-10%，海上风电项目约6%-8%（近海、大型化后向8%-10%改善）；136号文后电价市场化使IRR对电价假设的敏感性显著上升，优质项目（高风速+低造价+高绿电溢价）与普通项目的回报分化拉大。运营环节的代表公司包括龙源电力、三峡能源、中广核新能源、节能风电等，其估值逻辑更接近“类公用事业+碳资产期权”：股息率与装机成长是核心锚，绿电/CCER是估值弹性。')
P('综上，第2章的核心结论可概括为一句话：风电的“钱”已经从财政补贴切换为市场电价+机制保护+环境溢价的组合，谁能以最低成本获取资源、以最高效率运营项目，谁就能在全面入市时代赚到超额收益；设备环节的降本能力（大型化、国产化）与运营环节的精细化能力，是贯穿整个“十五五”的两条主线。')

